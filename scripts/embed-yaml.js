#!/usr/bin/env node
// Embed miner/miner.yaml into the Worker so it can serve the exact text at
// GET /miner.yaml (the Workers runtime has no filesystem). Run after editing
// the YAML; test/miner.test.js fails if the two drift apart.
import { readFileSync, writeFileSync } from "node:fs";

const yaml = readFileSync(new URL("../miner/miner.yaml", import.meta.url), "utf8");
writeFileSync(
  new URL("../miner/miner-yaml.generated.js", import.meta.url),
  `// Generated by scripts/embed-yaml.js from miner/miner.yaml. Do not edit.\nexport default ${JSON.stringify(yaml)};\n`,
);
