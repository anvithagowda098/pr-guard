#!/usr/bin/env node
// Refreshes src/ofac-addresses.js: every Ethereum-format address (0x + 40 hex)
// on the US Treasury's OFAC SDN list, with the listed party and program.
//
// PR Guard uses it as deterministic evidence for the sanctions check: a
// screening miner's answer alone never blocks a pull request, but the exact
// address on the official list does, whatever the miner said.
//
// Source: OFAC's SDN list (US government work, public domain). Addresses are in
// each entry's remarks ("Digital Currency Address - ETH 0x..."); remarks too
// long for SDN.CSV continue in SDN_COMMENTS.CSV.
//
//   node scripts/update-ofac.js
import { writeFile } from "node:fs/promises";

const BASE = "https://sanctionslistservice.ofac.treas.gov/api/PublicationPreview/exports/";

/** Minimal RFC 4180 parser: quoted fields, doubled quotes, newlines in quotes. */
export function parseCsv(text) {
  const rows = [];
  let row = [], field = "", quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const ADDRESS = /Digital Currency Address - ([A-Z0-9]+)\s+(0x[0-9a-fA-F]{40})\b/g;
const clean = (s) => String(s ?? "").trim().replace(/^-0-$/, "");

export function extractAddresses(sdnCsv, commentsCsv) {
  const entries = new Map(); // ent_num -> { name, program, remarks }
  for (const r of parseCsv(sdnCsv)) {
    if (r.length < 12) continue;
    // Programs read "SDGT] [ILLICIT-DRUGS-EO14059" in the CSV.
    entries.set(clean(r[0]), { name: clean(r[1]), program: clean(r[3]).replace(/\]\s*\[/g, ", "), remarks: clean(r[11]) });
  }
  for (const r of parseCsv(commentsCsv)) {
    const e = entries.get(clean(r[0]));
    if (e && r[1]) e.remarks += " " + r[1];
  }
  const out = {};
  for (const e of entries.values()) {
    for (const m of e.remarks.matchAll(ADDRESS)) {
      out[m[2].toLowerCase()] ??= [e.name, e.program, m[1]];
    }
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

async function get(name) {
  const r = await fetch(BASE + name, { headers: { "user-agent": "pr-guard-ofac-snapshot" } });
  if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
  return new TextDecoder("latin1").decode(await r.arrayBuffer());
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const addresses = extractAddresses(await get("SDN.CSV"), await get("SDN_COMMENTS.CSV"));
  const date = new Date().toISOString().slice(0, 10);
  const lines = Object.entries(addresses).map(([a, v]) => `  "${a}": ${JSON.stringify(v)},`);
  await writeFile(new URL("../src/ofac-addresses.js", import.meta.url), `// Generated by scripts/update-ofac.js from the US Treasury's OFAC SDN list
// (public domain). Do not edit by hand; rerun the script to refresh.
// Ethereum-format addresses only: address -> [listed party, program, currency].
export const OFAC_SNAPSHOT_DATE = "${date}";
export const OFAC_SOURCE = "${BASE}SDN.CSV";
export const OFAC_ADDRESSES = {
${lines.join("\n")}
};
`);
  console.log(`${Object.keys(addresses).length} addresses, snapshot ${date}`);
}
